import AppKit
import CryptoKit
import Observation
import SwiftUI
import Vision

/// Clipboard history: text, rich text, pictures (their words found by on-device text recognition) and copied files.
/// Repeats are merged with a count; pinned clips stay; the rest go after a week. Passwords are never kept.
@Observable
final class ClipboardHistory {
    // Explicit: an implicit deinit here becomes main-actor isolated and aborts on macOS 15.
    nonisolated deinit {}
    struct Clip: Codable, Identifiable, Equatable {
        enum Kind: String, Codable { case text, rich, image, files }
        var id = UUID()
        var kind: Kind
        var text: String           // the words searched and shown (file names for files, recognized text for pictures)
        var rtf: Data?
        var imageFile: String?     // picture stored as a PNG beside the history file
        var paths: [String]?
        var key: String            // fingerprint of the content, for merging repeats
        var count = 1
        var pinned = false
        var last: Date

        /// What the library's sidebar files it under, worked out from the content.
        enum Category: String, CaseIterable { case text = "Text", pictures = "Pictures", links = "Links", files = "Files", code = "Code", colors = "Colors" }
        var category: Category {
            switch kind {
            case .image: return .pictures
            case .files: return .files
            case .text, .rich:
                // the start is enough to tell, and keeps a 1 MB clip cheap to sort on every redraw
                let t = String(text.prefix(2000)).trimmingCharacters(in: .whitespacesAndNewlines)
                if t.range(of: #"^(#[0-9a-fA-F]{3}|#[0-9a-fA-F]{6}|#[0-9a-fA-F]{8}|rgba?\([0-9., %]+\))$"#, options: .regularExpression) != nil { return .colors }
                if !t.contains(where: \.isWhitespace), let u = URL(string: t), ["http", "https"].contains(u.scheme?.lowercased() ?? ""), u.host != nil { return .links }
                // shortcut: two or more telltale marks on a multi-line clip, not real language detection; enough to sort a history
                if t.contains("\n"), ["{", "};", "=>", "func ", "def ", "import ", "</", "const ", "return "].filter(t.contains).count >= 2 { return .code }
                return .text
            }
        }
    }

    var keepFor: TimeInterval = 7 * 24 * 3600   // set from Settings
    /// How many unpinned clips are kept (Settings: 200, 1,000 or 5,000).
    var maxClips = 200
    /// Pasteboard markers that password managers and similar apps set (nspasteboard.org).
    static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                            "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"]

    private(set) var clips: [Clip] = []
    var query = "" { didSet { selectedID = nil } }
    /// The clip the arrow keys are on; kept by id so pinning or a new copy does not move the ring to another clip.
    var selectedID: Clip.ID?
    /// Its place in `visible`; the first tile when nothing is picked.
    var selected: Int {
        get { visible.firstIndex { $0.id == selectedID } ?? 0 }
        set { selectedID = visible.indices.contains(newValue) ? visible[newValue].id : nil }
    }
    private let dir: URL?
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    init(dir: URL?, live: Bool) {
        self.dir = dir
        if let f = file, let data = try? Data(contentsOf: f) { clips = (try? JSONDecoder().decode([Clip].self, from: data)) ?? [] }
        prune()
        guard live else { return }
        // The Mac has no "clipboard changed" signal; a cheap counter check twice a second is the standard way.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll(.general) }
        timer?.tolerance = 0.25
    }

    private var file: URL? { dir?.appendingPathComponent("clipboard.json") }
    private func imageURL(_ name: String) -> URL? { dir?.appendingPathComponent("clipboard-images").appendingPathComponent(name) }

    func poll(_ pb: NSPasteboard) {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard let c = read(pb) else { return }
        add(c)
        shrinkCopied(c, on: pb)
    }

    /// The level copied pictures are shrunk at (Settings > Screenshots), nil when off; set only in the live app.
    @ObservationIgnored var shrinkLevel: (() -> ShrinkLevel?)?

    /// Puts a smaller copy of a copied picture back on the clipboard (as Clop did), unless something else was copied meanwhile.
    private func shrinkCopied(_ c: Clip, on pb: NSPasteboard) {
        // only a plain picture: a copy from a drawing app also carries its own editable data, which must not be lost
        let plain: Set<NSPasteboard.PasteboardType> = [.png, .tiff, .init("Apple PNG pasteboard type"), .init("NeXT TIFF v4.0 pasteboard type")]
        guard c.kind == .image, Set(pb.types ?? []).isSubset(of: plain), let level = shrinkLevel?(), let f = c.imageFile, let url = imageURL(f) else { return }
        let change = pb.changeCount
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            guard let png = try? Data(contentsOf: url), let small = PNGShrinker.shrink(png, level) else { return }
            DispatchQueue.main.async {
                guard let self, pb.changeCount == change else { return }
                pb.clearContents()
                pb.setData(small, forType: .png)
                self.lastChange = pb.changeCount
            }
        }
    }

    /// The newest clip on a pasteboard, or nil for private or empty ones.
    func read(_ pb: NSPasteboard, now: Date = Date()) -> Clip? {
        let types = pb.types ?? []
        if types.contains(where: { Self.privateTypes.contains($0.rawValue) }) { return nil }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Clip(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: ", "), paths: paths,
                        key: fingerprint(Data(paths.joined(separator: "\n").utf8)), last: now)
        }
        if let s = pb.string(forType: .string), !s.isEmpty {
            guard s.utf8.count <= 1_000_000 else { return nil }   // a huge copy (a whole log) would be rewritten to disk on every copy
            let rtf = pb.data(forType: .rtf)
            return Clip(kind: rtf == nil ? .text : .rich, text: s, rtf: rtf, key: fingerprint(Data(s.utf8)), last: now)
        }
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count < 20_000_000,
           let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
            let key = fingerprint(png)
            if !clips.contains(where: { $0.key == key }), let url = imageURL(key + ".png") {
                try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true,
                                                         attributes: [.posixPermissions: 0o700])
                try? png.write(to: url, options: .atomic)
                recognizeText(in: png, key: key)
            }
            return Clip(kind: .image, text: "", imageFile: key + ".png", key: key, last: now)
        }
        return nil
    }

    func add(_ c: Clip) {
        if let i = clips.firstIndex(where: { $0.key == c.key }) {
            var old = clips.remove(at: i)
            old.count += 1
            old.last = c.last
            clips.insert(old, at: 0)
        } else {
            clips.insert(c, at: 0)
        }
        prune(now: c.last)
    }

    /// Unpinned clips older than `keepFor` go, and only the newest `maxClips` unpinned stay. Their pictures are deleted with them.
    func prune(now: Date = Date()) {
        var unpinned = 0
        let keep = clips.filter { c in
            if c.pinned { return true }
            unpinned += 1
            return unpinned <= maxClips && now.timeIntervalSince(c.last) <= keepFor
        }
        let kept = Set(keep.map(\.id))
        for gone in clips where !kept.contains(gone.id) {
            if let f = gone.imageFile, let url = imageURL(f) { try? FileManager.default.removeItem(at: url) }
        }
        clips = keep
        savePrivately(clips, to: file)
    }

    func togglePin(_ c: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == c.id }) else { return }   // by id: the library holds older copies
        clips[i].pinned.toggle()
        savePrivately(clips, to: file)
    }

    /// Deletes a clip (and its picture) from the history.
    func remove(_ c: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == c.id }) else { return }
        if let f = clips[i].imageFile, let url = imageURL(f) { try? FileManager.default.removeItem(at: url) }
        clips.remove(at: i)
        savePrivately(clips, to: file)
    }

    /// Puts a clip back on the clipboard (without counting it as a new copy).
    func copy(_ c: Clip, to pb: NSPasteboard = .general) {
        pb.clearContents()
        switch c.kind {
        case .text: pb.setString(c.text, forType: .string)
        case .rich:
            if let rtf = c.rtf { pb.setData(rtf, forType: .rtf) }
            pb.setString(c.text, forType: .string)
        case .image: if let img = image(c) { pb.writeObjects([img]) }
        case .files: pb.writeObjects((c.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        if pb == .general { lastChange = pb.changeCount }
    }

    /// Pictures read once; the shelf and library redraw on every key press.
    private let images = NSCache<NSString, NSImage>()
    func image(_ c: Clip) -> NSImage? {
        guard let f = c.imageFile else { return nil }
        if let hit = images.object(forKey: f as NSString) { return hit }
        guard let url = imageURL(f), let img = NSImage(contentsOf: url) else { return nil }
        images.setObject(img, forKey: f as NSString)
        return img
    }

    /// What a clip looks like: the picture itself, or for copied files the first file
    /// (a picture file shows as itself, any other file as its Finder icon). Nil when the file is gone.
    func preview(_ c: Clip) -> NSImage? {
        guard c.kind == .files else { return image(c) }
        guard let path = c.paths?.first, FileManager.default.fileExists(atPath: path) else { return nil }
        if let hit = images.object(forKey: path as NSString) { return hit }
        // shortcut: files over 20 MB show their icon (reading them would stall the window); use QuickLook thumbnails if that matters
        let small = ((try? FileManager.default.attributesOfItem(atPath: path)[.size] as? Int) ?? .max) < 20_000_000
        let img = (small ? NSImage(contentsOfFile: path) : nil) ?? NSWorkspace.shared.icon(forFile: path)
        images.setObject(img, forKey: path as NSString)
        return img
    }

    /// Pinned first, then newest; filtered by the search words.
    var visible: [Clip] {
        let hits = Self.matching(clips, query)
        return hits.filter(\.pinned) + hits.filter { !$0.pinned }
    }

    /// The clips whose words contain the search, in the order given.
    static func matching(_ clips: [Clip], _ query: String) -> [Clip] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return q.isEmpty ? clips : clips.filter { $0.text.localizedCaseInsensitiveContains(q) }
    }

    /// The tile place after an arrow key in a grid `columns` wide, kept on a real tile.
    static func moved(_ i: Int, _ key: KeyEquivalent, count: Int, columns: Int) -> Int {
        guard count > 0 else { return 0 }
        let step = switch key {
        case .leftArrow: -1
        case .rightArrow: 1
        case .upArrow: -columns
        case .downArrow: columns
        default: 0
        }
        return min(max(i + step, 0), count - 1)
    }

    private func fingerprint(_ d: Data) -> String { SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined() }

    /// Finds the words in a copied picture on the Mac itself (Vision), so the picture can be searched.
    private func recognizeText(in png: Data, key: String) {
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let request = VNRecognizeTextRequest()
            try? VNImageRequestHandler(data: png).perform([request])
            let words = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: " ")
            guard !words.isEmpty else { return }
            DispatchQueue.main.async {
                guard let self, let i = self.clips.firstIndex(where: { $0.key == key }) else { return }
                self.clips[i].text = words
                savePrivately(self.clips, to: self.file)
            }
        }
    }
}

struct ClipboardPage: View {
    let model: ShelfModel   // the search field sits in the shelf's top row, right of the notch
    static let shelfColumns = 4
    private let columns = Array(repeating: GridItem(.flexible(), spacing: 8), count: Self.shelfColumns)

    var body: some View {
        @Bindable var history = model.clipboard
        VStack(spacing: 8) {
            if history.visible.isEmpty {
                Text(history.query.isEmpty ? "Things you copy show up here." : "Nothing matches.")
                    .font(Look.small).foregroundStyle(Look.dim).frame(maxWidth: .infinity, minHeight: 96)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVGrid(columns: columns, spacing: 8) {
                            ForEach(Array(history.visible.enumerated()), id: \.element.id) { i, c in tile(c, selected: i == history.selected) }
                        }
                    }
                    .scrollIndicators(.never)
                    .onChange(of: history.selected) { _, i in
                        if history.visible.indices.contains(i) { proxy.scrollTo(history.visible[i].id) }
                    }
                }
            }
            HStack {
                Spacer()
                Button("Open library") { model.openLibrary?() }
                    .buttonStyle(.plain).font(Look.small).foregroundStyle(Look.blue)
                    .help("The whole history in a big window" + (ShortcutManager.shared.shortcuts[.shelfLibrary].map { " (\($0.displayString))" } ?? ""))
            }
        }
    }

    private func tile(_ c: ClipboardHistory.Clip, selected: Bool) -> some View {
        let history = model.clipboard
        return Button {
            model.use(c, paste: !NSEvent.modifierFlags.contains(.option))   // ⌥-click only copies
        } label: {
            ZStack(alignment: .bottomTrailing) {
                Group {
                    if c.kind == .image, let img = history.image(c) {
                        // the tile's own size, filled by the picture and cut to it, so a wide picture never spills onto the next tile
                        Color.clear.overlay { Image(nsImage: img).resizable().aspectRatio(contentMode: .fill) }
                    } else if c.kind == .files, let img = history.preview(c) {
                        Image(nsImage: img).resizable().aspectRatio(contentMode: .fit).padding(6)
                    } else {
                        Text(c.kind == .files ? "Files: " + c.text : c.text)
                            .font(Look.small).padding(8)
                            .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                    }
                }
                .frame(maxWidth: .infinity).frame(height: 100).clipped()
                Text(c.pinned ? "pinned" : c.count > 1 ? "x\(c.count)" : c.kind == .image ? "image" : "")
                    .font(.system(size: 10)).foregroundStyle(Look.dim).padding(.trailing, 6).padding(.bottom, 4)
            }
            .background(Look.cardGradient)
            .clipShape(RoundedRectangle(cornerRadius: 14))
            .overlay(RoundedRectangle(cornerRadius: 14).strokeBorder(selected ? Look.blue : c.pinned ? Look.orange : .clear, lineWidth: 1.5))
            .contentShape(RoundedRectangle(cornerRadius: 14))
        }
        .buttonStyle(.plain)
        .contextMenu { Button(c.pinned ? "Unpin" : "Pin") { history.togglePin(c) } }
        .help("Click to paste, ⌥-click to copy")
        .accessibilityLabel((c.pinned ? "Pinned: " : "") + (c.text.isEmpty ? "Picture" : c.text))
        .accessibilityHint("Pastes it into the app you were in")
        .accessibilityAddTraits(selected ? .isSelected : [])
    }
}
